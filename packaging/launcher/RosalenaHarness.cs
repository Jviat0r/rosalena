// Rosalena Harness - stage 1 launcher.
//
// This is the ".exe" half of the product, and it is deliberately small. It does
// NOT bundle Node or the harness source: it locates them, hands the caller's
// arguments to the real CLI, and returns the child's exit code. Everything that
// decides anything lives in the harness; this file only makes the thing startable
// from a single path.
//
// Two personalities, chosen by how it was started:
//
//   * no arguments (a double-click) - open the desktop window: run the Electron app in
//     ..\desktop when it is installed. The window needs no Node.js, so this works even
//     on a machine without node.exe. If Electron is not installed, it says so and
//     falls back to the terminal client when there is a terminal to fall back to.
//   * any arguments - hand them to the real CLI.
//
// SUBYSTEM: this file is compiled as a GUI (Windows) subsystem binary - see
// packaging\build-exe.ps1, which passes /target:winexe. Windows therefore never
// allocates a console for a double-click: there is no black window behind the app and
// none that flashes and disappears. A launcher compiled as /target:exe *always* gets a
// console, which is exactly the bug this replaces.
//
//   * The child's stdout/stderr are redirected into a log file - <data>\logs\launcher.log,
//     where <data> is ROSALENA_HOME or <product>\data - and the file is rotated to
//     launcher.log.1 when it passes 2 MB, so the pair is bounded at ~4 MB.
//   * A GUI binary has no stdio, so "cannot find node" is a MessageBox, not a silent
//     failure. --no-dialog (or ROSALENA_LAUNCHER_NO_DIALOG=1) suppresses that for
//     unattended callers.
//
// RUNNING IT FROM A TERMINAL: the launcher attaches to the terminal it was started
// from and mirrors everything it logs and everything the child prints, so
// `Rosalena-Harness.exe --check` still shows its output in the same window. Two flags
// are for the cases where the launcher has no console to attach to:
//
//   --console  allocate a console if none is attached (a double-click with this flag
//              opens one), then mirror logs and child output into it.
//   --log      print (and dialog-box) the path of the log file and its last 40 lines.
//
// Terminal output is line-based and is not a TTY: the child's stdio is a pipe, so an
// interactive prompt or ANSI colour is not the same as running `node src\cli.mjs`
// directly. The launcher forwards one Ctrl+C to the child and then reports the child's
// real exit code.
//
// What it buys over `node src/cli.mjs`:
//   * one thing to double-click, with a real name and a real icon
//   * a window on a machine that has never had Node installed
//   * a clear message (not a stack trace) when Node or the source is missing
//   * a Node version check before the ESM import fails cryptically
//   * one log file that holds both the launcher's and the child's output
//   * Ctrl+C forwarded to the child instead of orphaning it
//   * the install layout is derived from this file's own location, so moving the
//     product folder does not break it
//
// The icon is packaging\assets\rosalena.ico, generated by packaging\tools\make-icon.mjs
// and embedded with /win32icon - regenerate it, never hand-edit the .ico.
//
// Build: packaging\build-exe.ps1 (uses the in-box .NET Framework csc.exe).
// C# 5 only - this is compiled by the Framework compiler, so no string
// interpolation, no expression-bodied members, no null-conditional operator.

using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.Globalization;
using System.IO;
using System.Reflection;
using System.Runtime.InteropServices;
using System.Text;

[assembly: AssemblyTitle("Rosalena Harness")]
[assembly: AssemblyDescription("Launcher for the Rosalena Harness agent runtime (desktop window and Node.js CLI).")]
[assembly: AssemblyProduct("Rosalena Harness")]
[assembly: AssemblyCompany("Rosalena")]
[assembly: AssemblyVersion("0.1.0.0")]
[assembly: AssemblyFileVersion("0.1.0.0")]

internal static class RosalenaHarnessLauncher
{
    // Distinct, documented exit codes: a caller (or another harness) can tell a
    // broken install from a failed task without parsing our prose. A task's own
    // exit code is never one of these - it is whatever the harness returned.
    private const int ExitBadInstall = 2;
    private const int ExitNoNode = 3;
    private const int ExitNodeTooOld = 4;
    private const int ExitNoDesktop = 5;

    // Console handles, as GetStdHandle() numbers them.
    private const int StdInputHandle = -10;
    private const int StdOutputHandle = -11;
    private const int StdErrorHandle = -12;
    private const uint AttachParentProcess = 0xFFFFFFFF;

    // MessageBox: OK, error/information icon, and foreground so it is not lost behind
    // other windows when a second launch happens.
    private const uint MbOk = 0x0;
    private const uint MbIconError = 0x10;
    private const uint MbIconInformation = 0x40;
    private const uint MbSetForeground = 0x10000;

    // The log is bounded, not rotated on a schedule: one 2 MB file plus one 2 MB
    // previous file, so a machine that runs this for a year still has a 4 MB ceiling.
    private const long MaxLogBytes = 2L * 1024L * 1024L;
    private const int LogTailLines = 40;

    private static readonly object LogLock = new object();
    private static TextWriter logWriter = TextWriter.Null;
    private static string logFile = null;
    // A console is attached (or allocated) and stdout could be rebound, so log lines
    // can also be mirrored to the terminal instead of only reaching the file.
    private static bool mirror;
    private static bool consoleAttached;
    private static bool consoleOwned;   // allocated by this process - it dies with us
    private static bool consolePaused;  // the single "press Enter" a failed or owned console gets
    private static bool dialogs;

    private static int Main(string[] args)
    {
        bool wantConsole = HasFlag(args, "--console");

        // Attach to the terminal this was started from, if there is one. A double-click
        // from Explorer has no parent console and nothing is created - that is the whole
        // point of the winexe subsystem. Only --console asks for one: --log reports
        // through a dialog when there is no terminal, because a console that lives and
        // dies with a process that is finished talking cannot be read.
        consoleAttached = AttachConsole(AttachParentProcess);
        if (!consoleAttached && wantConsole)
        {
            consoleAttached = AllocConsole();
            consoleOwned = consoleAttached;
        }
        bool stdio = RebindStdio();
        mirror = consoleAttached || stdio;
        dialogs = !HasFlag(args, "--no-dialog") &&
                  (Environment.GetEnvironmentVariable("ROSALENA_LAUNCHER_NO_DIALOG") ?? "").Length == 0 &&
                  Environment.UserInteractive;

        string exePath = Assembly.GetExecutingAssembly().Location;
        string exeDir = Path.GetDirectoryName(exePath);
        string productRoot = ResolveProductRoot(exeDir);

        string harnessDir = Environment.GetEnvironmentVariable("ROSALENA_HARNESS");
        if (harnessDir == null || harnessDir.Length == 0)
        {
            harnessDir = Path.Combine(productRoot, "harness");
        }
        harnessDir = Path.GetFullPath(harnessDir);

        // Keep the suite's own state beside the product instead of in the user's
        // home. Two reasons: the folder stays self-contained and movable, and a
        // sandboxed (Low integrity) process - which is what an .exe inside a
        // sandboxed workspace is - may only write inside its own tree, so
        // memory/ledger/registry writes to %USERPROFILE% fail with EPERM there.
        // An explicit ROSALENA_HOME from the caller always wins.
        string dataDir = Environment.GetEnvironmentVariable("ROSALENA_HOME");
        if (dataDir == null || dataDir.Length == 0)
        {
            dataDir = Path.Combine(productRoot, "data");
        }
        dataDir = Path.GetFullPath(dataDir);
        try
        {
            Directory.CreateDirectory(dataDir);
        }
        catch (Exception)
        {
            // A read-only product folder must not stop the run; the harness
            // reports whatever it cannot write.
        }

        OpenLog(Path.Combine(dataDir, "logs"));
        Log("");
        Log("=== " + Timestamp() + " launcher start ===");
        Log("  exe      " + exePath);
        Log("  args     " + JoinArgs(args));
        Log("  console  " + DescribeConsole());
        Log("  log      " + logFile);

        string cli = Path.Combine(harnessDir, "src", "cli.mjs");
        string ui = Path.Combine(harnessDir, "src", "ui.mjs");
        string desktopApp = Path.Combine(productRoot, "desktop");
        string electron = FindElectron(desktopApp);
        string node = FindNode();

        // Launcher-only flags never reach the harness: it has no --console, --log or
        // --no-dialog, and a stray flag would be taken for a task description.
        string[] childArgs = StripLauncherFlags(args);

        // --launcher-info answers "which node, which source am I actually running?"
        // without starting a session. Support question number one, one flag away.
        if (childArgs.Length == 1 && childArgs[0] == "--launcher-info")
        {
            string[] report = new string[]
            {
                "Rosalena Harness launcher " + LauncherVersion(),
                "  launcher  " + exePath,
                "  product   " + productRoot,
                "  harness   " + harnessDir + (File.Exists(cli) ? " (found)" : " (NO src/cli.mjs)"),
                "  node      " + (node == null ? "(not found)" : node),
                "  desktop   " + desktopApp + DescribeDesktop(electron, ui),
                "  data      " + dataDir,
                "  log       " + logFile,
                "  console   " + DescribeConsole(),
                "  cwd       " + Environment.CurrentDirectory,
            };
            Report(report);
            bool ok = electron != null || (File.Exists(cli) && node != null);
            Log("  result    " + (ok ? "ok" : "incomplete install"));
            PauseOwnedConsole();
            return ok ? 0 : ExitBadInstall;
        }

        // --log is the "why did nothing happen?" answer for a double-clicked app: the
        // log file, and its tail, without needing a terminal to find it.
        if (HasFlag(args, "--log"))
        {
            ShowLog();
            PauseOwnedConsole();
            return 0;
        }

        bool noArguments = childArgs.Length == 0;

        // The window is the default double-click answer: it is the thing people mean
        // when they click the product, and it needs nothing from Node. Arguments keep
        // meaning "run this task", so scripting is unchanged.
        bool askForDesktop = noArguments || (childArgs.Length == 1 && childArgs[0] == "--desktop");
        if (askForDesktop)
        {
            string gap = electron == null ? "electron" : (!File.Exists(ui) ? "ui" : null);
            if (gap == null)
            {
                int windowCode = RunDesktop(electron, desktopApp, dataDir);
                PauseOwnedConsole();
                return windowCode;
            }

            string[] why = new string[]
            {
                "Rosalena Harness cannot open its window.",
                "  app folder: " + desktopApp,
                "  " + (gap == "electron"
                    ? "no Electron runtime has been installed there yet"
                    : "the engine file is missing: " + ui),
                "  install it once:  cd \"" + desktopApp + "\"  &&  npm install",
                "  (that first install needs internet; the window itself runs offline)",
            };

            // A double-click cannot fall back to a terminal client: there is no console
            // to type into, so the instruction would be invisible. Say it in a dialog
            // and stop; from a terminal, keeping the old fall-through is still useful.
            if (!noArguments || !mirror)
            {
                Fail(ExitNoDesktop, why);
                return ExitNoDesktop;
            }

            Log("  window   unavailable" + DescribeDesktop(electron, ui));
            Log("  falling back to the terminal client (a console is attached)");
        }

        if (!File.Exists(cli))
        {
            Fail(ExitBadInstall,
                "Rosalena Harness cannot find its runtime.",
                "  looked for: " + cli,
                "  the launcher lives in " + exeDir,
                "  and expects the harness package in a folder beside it: " + productRoot + "\\harness",
                "  if you moved the harness, set ROSALENA_HARNESS to its directory.");
            return ExitBadInstall;
        }

        if (node == null)
        {
            Fail(ExitNoNode,
                "Rosalena Harness needs Node.js and could not find node.exe.",
                "  install Node.js 20 or newer (https://nodejs.org), or set ROSALENA_NODE",
                "  to the full path of node.exe, e.g. C:\\Program Files\\nodejs\\node.exe",
                "  the harness has no native dependencies - Node is the only prerequisite.");
            return ExitNoNode;
        }

        int major = NodeMajorVersion(node);
        if (major > 0 && major < 20)
        {
            Fail(ExitNodeTooOld,
                "Rosalena Harness needs Node.js 20 or newer.",
                "  found: " + node + " (v" + major + ")",
                "  install a newer Node.js, or point ROSALENA_NODE at one.");
            return ExitNodeTooOld;
        }

        StringBuilder commandLine = new StringBuilder();
        commandLine.Append(Quote(cli));
        for (int i = 0; i < childArgs.Length; i++)
        {
            commandLine.Append(' ');
            commandLine.Append(Quote(childArgs[i]));
        }

        // The caller's working directory is the harness's default workspace. A
        // launcher that silently changed it would make `--root` mean something
        // different depending on how the tool was started.
        ProcessStartInfo run = ChildStartInfo(node, commandLine.ToString(), Environment.CurrentDirectory, dataDir);
        Log("  child    " + node + " " + commandLine.ToString());

        Exception failure;
        int code = RunProcess("the harness", run, out failure);
        if (failure != null)
        {
            Fail(ExitBadInstall,
                "Rosalena Harness could not start Node.",
                "  node: " + node,
                "  " + failure.Message);
            return ExitBadInstall;
        }

        Log("  exit     " + code + " (" + Timestamp() + ")");
        PauseOwnedConsole();
        return code;
    }

    // ------------------------------------------------------------------ the child

    /// <summary>
    /// One place that decides how a child process is started. The launcher is a
    /// winexe, so a console child would get a brand-new console window unless it is
    /// suppressed: CreateNoWindow is true whenever this process has no console to
    /// share. When it *does* have one (a terminal run), the child shares it instead, so
    /// a tool the agent runs does not mint a visible console either - and Ctrl+C
    /// reaches the harness directly.
    /// </summary>
    private static ProcessStartInfo ChildStartInfo(string file, string arguments, string workingDirectory, string dataDir)
    {
        ProcessStartInfo psi = new ProcessStartInfo(file);
        psi.Arguments = arguments;
        psi.UseShellExecute = false;
        psi.CreateNoWindow = !consoleAttached;
        // SW_HIDE only applies to a window that would be created. When the child shares
        // the user's terminal there is nothing to hide, and hiding the terminal is the
        // one outcome that must never happen.
        psi.WindowStyle = consoleAttached ? ProcessWindowStyle.Normal : ProcessWindowStyle.Hidden;
        psi.RedirectStandardOutput = true;
        psi.RedirectStandardError = true;
        // node writes UTF-8 to a pipe; the default here is the machine's ANSI code page,
        // which would turn the harness's box drawing into mojibake in the log.
        psi.StandardOutputEncoding = new UTF8Encoding(false);
        psi.StandardErrorEncoding = new UTF8Encoding(false);
        psi.WorkingDirectory = workingDirectory;
        psi.EnvironmentVariables["ROSALENA_HOME"] = dataDir;
        return psi;
    }

    /// <summary>
    /// Runs a child to completion with its output teed into the log, and returns its
    /// exit code. A start failure comes back through <paramref name="failure"/> rather
    /// than an exception, so each caller can phrase the message for what it tried to
    /// start.
    /// </summary>
    private static int RunProcess(string what, ProcessStartInfo psi, out Exception failure)
    {
        failure = null;
        int code = -1;
        using (Process child = new Process())
        {
            child.StartInfo = psi;
            child.OutputDataReceived += OnChildOutput;
            child.ErrorDataReceived += OnChildError;

            // Ctrl+C is delivered to every process in the console group, so the child
            // gets it too when it shares a console. Swallowing it here keeps this
            // process alive to report the child's real exit code instead of dying
            // first and orphaning it; when the child has no console (the usual case),
            // killing it here is what stops it.
            ConsoleCancelEventHandler onCancel = delegate(object sender, ConsoleCancelEventArgs e)
            {
                e.Cancel = true;
                LogError("[launcher] Ctrl+C - stopping " + what + " ...");
                try
                {
                    if (child.Id != 0 && !child.HasExited) child.Kill();
                }
                catch (Exception) { }
            };

            Console.CancelKeyPress += onCancel;
            try
            {
                if (!child.Start()) throw new InvalidOperationException("the process could not be started");
                child.BeginOutputReadLine();
                child.BeginErrorReadLine();
                child.WaitForExit();
                // The second wait is the documented way to know the asynchronous output
                // handlers have delivered every last line; without it the log can lose
                // the child's final words.
                child.WaitForExit();
                code = child.ExitCode;
            }
            catch (Exception ex)
            {
                failure = ex;
            }
            finally
            {
                Console.CancelKeyPress -= onCancel;
            }
        }
        return code;
    }

    private static void OnChildOutput(object sender, DataReceivedEventArgs e)
    {
        if (e.Data != null) Log(e.Data);
    }

    private static void OnChildError(object sender, DataReceivedEventArgs e)
    {
        if (e.Data != null) LogError(e.Data);
    }

    /// <summary>
    /// Starts the window and waits for it: the launcher is not a background service, and
    /// its exit code should say what happened to the window. There is no console to
    /// hide - the binary is a GUI subsystem one - and the window's own output goes to
    /// the same log as everything else.
    /// </summary>
    private static int RunDesktop(string executable, string desktopApp, string dataDir)
    {
        // A bare electron.exe needs to be told which app to run; a packaged build already
        // contains it.
        bool packaged = !string.Equals(Path.GetFileName(executable), "electron.exe", StringComparison.OrdinalIgnoreCase);

        ProcessStartInfo run = ChildStartInfo(executable, packaged ? "" : Quote(desktopApp), desktopApp, dataDir);
        // A window that runs as Node is not a window: with ELECTRON_RUN_AS_NODE set,
        // electron.exe behaves like plain `node`, the `electron` module imports as an
        // empty object and the process dies with a SyntaxError before any window exists.
        // Some shells export it (VS Code's integrated terminal, various automation
        // images), and a launch from one of them would otherwise fail with nothing on
        // screen. The window is never a Node script, so the variable is dropped here;
        // the CLI path leaves the caller's environment alone.
        run.EnvironmentVariables.Remove("ELECTRON_RUN_AS_NODE");
        Log("  child    " + executable + (packaged ? "" : " " + Quote(desktopApp)));

        Exception failure;
        int code = RunProcess("the window", run, out failure);
        if (failure != null)
        {
            Fail(ExitNoDesktop,
                "Rosalena Harness could not start the window.",
                "  runtime " + executable,
                "  " + failure.Message,
                "  if the runtime is broken, reinstall it:  cd \"" + desktopApp + "\"  &&  npm install");
            return ExitNoDesktop;
        }

        // A window that closes normally exits 0. Anything else is worth knowing about,
        // and a launch with no console has no other way to say it.
        if (code != 0)
        {
            Fail(code,
                "Rosalena Harness: the window exited with code " + code + ".",
                "  runtime " + executable,
                "  the launcher's log has the window's own output.");
        }
        Log("  exit     " + code + " (" + Timestamp() + ")");
        return code;
    }

    // ------------------------------------------------------------------ reporting

    /// <summary>
    /// Every deliberate failure goes through here: it is one message with three sinks -
    /// the log file always, the terminal when there is one, and a dialog box when there
    /// is neither (a double-click, or a script with no stdio). Silence is the failure
    /// mode this replaces.
    /// </summary>
    private static void Fail(int code, params string[] lines)
    {
        LogError("");
        for (int i = 0; i < lines.Length; i++) LogError(lines[i]);
        LogError("");
        LogError("  log file  " + logFile);
        LogError("(exit " + code + ")");

        if (!mirror)
        {
            string text = string.Join(Environment.NewLine, lines) +
                          Environment.NewLine + Environment.NewLine +
                          "log file: " + logFile +
                          Environment.NewLine + "(exit " + code + ")";
            ShowDialog("Rosalena Harness", text, MbIconError);
        }

        // An allocated console disappears with this process, so leave it long enough to
        // be read. An attached terminal stays, so it is never paused.
        PauseOwnedConsole();
    }

    /// <summary>
    /// A console this process allocated exists only as long as the process does, so
    /// bolting on exit would make a --console run flash and vanish - the exact symptom
    /// the GUI subsystem was chosen to avoid. Wait for Enter, once. A terminal that was
    /// merely attached to is never paused: it belongs to the user.
    /// </summary>
    private static void PauseOwnedConsole()
    {
        if (!consoleOwned || consolePaused) return;
        consolePaused = true;
        try
        {
            Console.Out.WriteLine();
            Console.Out.WriteLine("Press Enter to close this console.");
            Console.Out.Flush();
            Console.ReadLine();
        }
        catch (Exception) { }
    }

    /// <summary>
    /// --launcher-info's sink: the log always, the console when available, and a dialog
    /// box when the launcher was started with neither (so the report is never lost).
    /// </summary>
    private static void Report(string[] lines)
    {
        for (int i = 0; i < lines.Length; i++) Log(lines[i]);
        if (!mirror)
        {
            ShowDialog("Rosalena Harness", string.Join(Environment.NewLine, lines), MbIconInformation);
        }
    }

    /// <summary>
    /// The tail of the log, printed and/or shown. This is the affordance for a window
    /// that will not start: everything the launcher and the window said is in one file.
    /// </summary>
    private static void ShowLog()
    {
        string size = "missing";
        try
        {
            FileInfo info = new FileInfo(logFile);
            if (info.Exists) size = info.Length.ToString("N0", CultureInfo.InvariantCulture) + " bytes";
        }
        catch (Exception) { }

        string[] tail = TailLines(logFile, LogTailLines);
        string[] head = new string[]
        {
            "Rosalena Harness launcher log",
            "  file  " + logFile,
            "  size  " + size + " (rotated to launcher.log.1 above 2 MB)",
            "  last  " + tail.Length + " lines",
        };

        for (int i = 0; i < head.Length; i++) Mirror(head[i]);
        for (int i = 0; i < tail.Length; i++) Mirror("  | " + tail[i]);

        if (mirror) return;
        StringBuilder text = new StringBuilder();
        for (int i = 0; i < head.Length; i++) text.AppendLine(head[i]);
        text.Append(string.Join(Environment.NewLine, tail));
        ShowDialog("Rosalena Harness launcher log", text.ToString(), MbIconInformation);
    }

    private static void ShowDialog(string caption, string text, uint icon)
    {
        if (!dialogs) return;
        try
        {
            MessageBoxW(IntPtr.Zero, text, caption, MbOk | icon | MbSetForeground);
        }
        catch (Exception) { }
    }

    private static string[] TailLines(string path, int count)
    {
        try
        {
            if (!File.Exists(path)) return new string[0];
            // FileShare.ReadWrite, deliberately: this file is open for writing by this very
            // process, and File.ReadAllLines() asks for FileShare.Read, which a live write
            // handle does not satisfy - the read fails with a sharing violation and the
            // report would say "last 0 lines".
            using (FileStream stream = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.ReadWrite))
            using (StreamReader reader = new StreamReader(stream, new UTF8Encoding(false)))
            {
                List<string> all = new List<string>();
                string line;
                while ((line = reader.ReadLine()) != null) all.Add(line);
                int take = Math.Min(count, all.Count);
                string[] tail = new string[take];
                all.CopyTo(all.Count - take, tail, 0, take);
                return tail;
            }
        }
        catch (Exception)
        {
            return new string[0];
        }
    }

    // ------------------------------------------------------------------ the log

    private static void OpenLog(string directory)
    {
        logFile = Path.Combine(directory, "launcher.log");
        try
        {
            Directory.CreateDirectory(directory);
            RotateLog(logFile);
            FileStream stream = new FileStream(logFile, FileMode.Append, FileAccess.Write, FileShare.ReadWrite);
            StreamWriter writer = new StreamWriter(stream, new UTF8Encoding(false));
            writer.AutoFlush = true;
            logWriter = writer;
        }
        catch (Exception)
        {
            // A read-only install must not stop the run, and neither must a log file
            // that another launcher holds open: the child still runs, only unlogged.
            logWriter = TextWriter.Null;
        }
    }

    private static void RotateLog(string path)
    {
        try
        {
            FileInfo current = new FileInfo(path);
            if (!current.Exists || current.Length < MaxLogBytes) return;
            string previous = path + ".1";
            if (File.Exists(previous)) File.Delete(previous);
            File.Move(path, previous);
        }
        catch (Exception) { }
    }

    private static void Log(string line)
    {
        lock (LogLock)
        {
            try { logWriter.WriteLine(line); } catch (Exception) { }
            if (!mirror) return;
            try
            {
                Console.Out.WriteLine(line);
                Console.Out.Flush();
            }
            catch (Exception) { }
        }
    }

    private static void LogError(string line)
    {
        lock (LogLock)
        {
            try { logWriter.WriteLine(line); } catch (Exception) { }
            if (!mirror) return;
            try
            {
                Console.Error.WriteLine(line);
                Console.Error.Flush();
            }
            catch (Exception) { }
        }
    }

    /// <summary>
    /// Console-only output, for text that came *out of* the log (see ShowLog): writing it
    /// back would add another forty lines to the file on every invocation.
    /// </summary>
    private static void Mirror(string line)
    {
        if (!mirror) return;
        lock (LogLock)
        {
            try
            {
                Console.Out.WriteLine(line);
                Console.Out.Flush();
            }
            catch (Exception) { }
        }
    }

    // ------------------------------------------------------------------ console

    /// <summary>
    /// After AttachConsole/AllocConsole the standard handles change (a GUI process
    /// starts with none), so Console.Out has to be rebound to the handle that now
    /// exists. Without this, everything written after the attach would go to the null
    /// stream the process started with.
    /// </summary>
    private static bool RebindStdio()
    {
        bool ok = false;
        if (IsUsableHandle(GetStdHandle(StdOutputHandle)))
        {
            try
            {
                SetConsoleOutputCP(65001);   // UTF-8, so the harness's box drawing survives
                StreamWriter writer = new StreamWriter(Console.OpenStandardOutput(), new UTF8Encoding(false));
                writer.AutoFlush = true;
                Console.SetOut(writer);
                ok = true;
            }
            catch (Exception) { }
        }
        if (IsUsableHandle(GetStdHandle(StdErrorHandle)))
        {
            try
            {
                StreamWriter writer = new StreamWriter(Console.OpenStandardError(), new UTF8Encoding(false));
                writer.AutoFlush = true;
                Console.SetError(writer);
                ok = true;
            }
            catch (Exception) { }
        }
        return ok;
    }

    private static bool IsUsableHandle(IntPtr handle)
    {
        return handle != IntPtr.Zero && handle.ToInt64() != -1;
    }

    private static string DescribeConsole()
    {
        if (consoleOwned) return "allocated by --console (no console was attached)";
        if (consoleAttached) return "attached to the terminal this was started from";
        if (mirror) return "none (stdout/stderr were redirected by the caller)";
        return "none (GUI subsystem: no console window exists, nothing to flash)";
    }


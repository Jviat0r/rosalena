    private static bool HasFlag(string[] args, string name)
    {
        for (int i = 0; i < args.Length; i++)
        {
            if (string.Equals(args[i], name, StringComparison.OrdinalIgnoreCase)) return true;
        }
        return false;
    }

    /// <summary>
    /// Drops the flags this file consumes, keeping every other argument in order and
    /// unmodified - a task description that happens to contain "--log" as its own word
    /// is the only thing this can misread, and that is documented rather than guessed
    /// at with prefix matching.
    /// </summary>
    private static string[] StripLauncherFlags(string[] args)
    {
        string[] dropped = new string[] { "--console", "--log", "--no-dialog" };
        int keep = 0;
        for (int i = 0; i < args.Length; i++)
        {
            if (Array.IndexOf(dropped, args[i]) < 0) keep++;
        }
        string[] result = new string[keep];
        int at = 0;
        for (int i = 0; i < args.Length; i++)
        {
            if (Array.IndexOf(dropped, args[i]) < 0) result[at++] = args[i];
        }
        return result;
    }

    private static string JoinArgs(string[] args)
    {
        if (args.Length == 0) return "(none)";
        StringBuilder text = new StringBuilder();
        for (int i = 0; i < args.Length; i++)
        {
            if (i > 0) text.Append(' ');
            text.Append(Quote(args[i]));
        }
        return text.ToString();
    }

    private static string Timestamp()
    {

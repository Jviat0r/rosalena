    /// <summary>
    /// Where the desktop shell's Electron runtime is, or null when it is not installed.
    /// The window lives in ..\desktop (an ordinary npm project); it is discovered, not
    /// bundled, so this launcher stays the same small file whether or not it is there.
    /// </summary>
    private static string FindElectron(string desktopApp)
    {
        // 1. An explicit runtime wins: this is how a packaged or moved copy is pointed
        //    at, and how the launcher is tested against a build.
        string explicitPath = Environment.GetEnvironmentVariable("ROSALENA_ELECTRON");
        if (!string.IsNullOrEmpty(explicitPath) && File.Exists(explicitPath)) return explicitPath;

        // 2. A packaged build (desktop\build.md, path A) carries its own runtime and its
        //    own copy of the app, so it is started on its own, without an app argument.
        string packaged = Path.Combine(desktopApp, "dist", "win-unpacked", "Rosalena Harness.exe");
        if (File.Exists(packaged)) return packaged;

        // 3. The npm install that `npm start` uses. path.txt is Electron's own record of
        //    the binary inside dist\ - trust it first, then the ordinary name.
        string electronPackage = Path.Combine(desktopApp, "node_modules", "electron");
        string distDir = Path.Combine(electronPackage, "dist");
        string record = Path.Combine(electronPackage, "path.txt");
        if (File.Exists(record))
        {
            try
            {
                string relative = File.ReadAllText(record).Trim();
                if (relative.Length > 0)
                {
                    string candidate = Path.GetFullPath(Path.Combine(distDir, relative.Replace('/', '\\')));
                    if (File.Exists(candidate)) return candidate;
                }
            }
            catch (Exception) { }   // unreadable record: fall through to the plain name
        }

        string plain = Path.Combine(distDir, "electron.exe");
        if (File.Exists(plain)) return plain;
        return null;
    }

    // One line, used by --launcher-info and by the "no window" message, so the reason a
    // double-click went to the terminal is never guesswork.
    private static string DescribeDesktop(string electron, string ui)
    {
        if (electron == null) return " (no Electron runtime - one-time install: npm install in the desktop folder)";
        if (!File.Exists(ui)) return " (window runtime " + electron + ", but " + ui + " is missing)";
        return " (window: " + electron + ")";
    }

    /// <summary>
    /// Two install layouts are supported, so the exe can sit at the product root
    /// (the obvious thing to double-click) or in bin\ (where it used to live).
    /// The test is "is there a harness folder here?", because that, not the folder's
    /// name, is what makes a directory the product root.
    /// </summary>
    private static string ResolveProductRoot(string exeDir)
    {
        if (Directory.Exists(Path.Combine(exeDir, "harness")))
        {
            return Path.GetFullPath(exeDir);
        }
        return Path.GetFullPath(Path.Combine(exeDir, ".."));
    }

    private static string FindNode()
    {
        string explicitPath = Environment.GetEnvironmentVariable("ROSALENA_NODE");
        if (!string.IsNullOrEmpty(explicitPath) && File.Exists(explicitPath)) return explicitPath;

        string path = Environment.GetEnvironmentVariable("PATH");
        if (!string.IsNullOrEmpty(path))
        {
            string[] dirs = path.Split(';');
            for (int i = 0; i < dirs.Length; i++)
            {
                string dir = dirs[i].Trim().Trim('"');
                if (dir.Length == 0) continue;
                try
                {
                    string candidate = Path.Combine(dir, "node.exe");
                    if (File.Exists(candidate)) return candidate;
                }
                catch (ArgumentException) { }   // malformed PATH entry - skip it
            }
        }

        string[] known = new string[]
        {
            Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.ProgramFiles), "nodejs", "node.exe"),
            Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.ProgramFilesX86), "nodejs", "node.exe"),
            Path.Combine(Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData), "Programs", "nodejs", "node.exe"),
        };
        for (int i = 0; i < known.Length; i++)
        {
            if (known[i] != null && known[i].Length > 0 && File.Exists(known[i])) return known[i];
        }
        return null;
    }

    // 0 means "could not tell" - never blocks a run on a probe that failed.
    private static int NodeMajorVersion(string node)
    {
        try
        {
            ProcessStartInfo psi = new ProcessStartInfo(node, "--version");
            psi.UseShellExecute = false;
            psi.RedirectStandardOutput = true;
            psi.RedirectStandardError = true;
            psi.CreateNoWindow = true;
            psi.WindowStyle = ProcessWindowStyle.Hidden;
            using (Process p = Process.Start(psi))
            {
                string text = p.StandardOutput.ReadToEnd();
                p.StandardError.ReadToEnd();
                p.WaitForExit(15000);
                text = text.Trim().TrimStart('v', 'V');
                int dot = text.IndexOf('.');
                if (dot > 0) text = text.Substring(0, dot);
                int major;
                if (int.TryParse(text, out major)) return major;
            }
        }
        catch (Exception) { }
        return 0;
    }


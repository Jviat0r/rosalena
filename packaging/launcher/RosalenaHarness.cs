    // The canonical Windows command-line quoting rule: backslashes are literal
    // except immediately before a quote, where they double. Getting this wrong
    // splits arguments on spaces, which is exactly the bug that makes a launcher
    // look like it works until someone runs it on a path with a space in it -
    // and this product's whole path has a space in it.
    private static string Quote(string argument)
    {
        if (argument.Length > 0 && argument.IndexOfAny(new char[] { ' ', '\t', '"', '\n', '\v', '\r' }) < 0) return argument;

        StringBuilder sb = new StringBuilder();
        sb.Append('"');
        int backslashes = 0;
        for (int i = 0; i < argument.Length; i++)
        {
            char c = argument[i];
            if (c == '\\')
            {
                backslashes++;
                sb.Append(c);
            }
            else if (c == '"')
            {
                sb.Append('\\', backslashes * 2 + 1);
                sb.Append('"');
                backslashes = 0;
            }
            else
            {
                backslashes = 0;
                sb.Append(c);
            }
        }
        sb.Append('\\', backslashes * 2);
        sb.Append('"');
        return sb.ToString();
    }

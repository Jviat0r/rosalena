test('harness.js: every sentence it hands to tr() has Spanish, and no vendor is named', () => {
  const source = read('harness/harness.js');
  const strings = tableFrom('harness/harness.js', 'STRINGS_ES');
  const wanted = new Set();
  // Every tr( call, single- or multi-line, and the English literals inside it.
  for (const block of source.matchAll(/\btr\((?:[^()]|\([^()]*\))*\)/gs)) {
    for (const match of block[0].matchAll(/'((?:[^'\\]|\\.)*)'/g)) {
      const text = match[1].replace(/\\'/g, "'");
      if (/\s/.test(text) || /^[A-Z]/.test(text)) wanted.add(text);
    }
  }
  const missing = [...wanted].filter((text) => !strings[text]);
  assert.deepEqual(missing, [], `harness.js STRINGS_ES lacks: ${missing.join(' | ')}`);
  for (const name of ['DeepSeek', 'deepseek', 'GLM', 'Claude', 'OpenAI', 'GPT']) {
    assert.equal(JSON.stringify(strings).includes(name), false);
  }
});


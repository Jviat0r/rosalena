// The Spanish site: /es/ pages built from the English ones by tools/build-i18n.mjs.
//
//   - the committed /es/ pages and the sitemap are exactly what a build writes now, and every
//     English string has Spanish (so an English edit without a rebuild fails here)
//   - each Spanish page carries its own lang, title, description, canonical, og:url, JSON-LD and
//     the hreflang trio, and the English page carries the same trio and a switch to it
//   - the Spanish pages keep the page rules the English ones are held to
//   - every script's Spanish table has the same entries as its English one
//
//   node --test test/i18n.test.mjs

import test from 'node:test';

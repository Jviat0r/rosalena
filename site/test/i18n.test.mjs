// ------------------------------------------------------------------ the pages crawlers read

const meta = (html, re) => re.exec(html)?.[1] ?? null;
const titleOf = (html) => meta(html, /<title>([^<]*)<\/title>/);
const descOf = (html) => meta(html, /<meta name="description" content="([^"]*)"/);
const canonOf = (html) => meta(html, /<link rel="canonical" href="([^"]+)"/);
const ogUrlOf = (html) => meta(html, /<meta property="og:url" content="([^"]+)"/);

for (const page of INDEXED) {
  const en = read(page.file);
  const es = read(`es/${page.file}`);

  test(`${page.route}: the Spanish page is its own page for crawlers`, () => {
    assert.match(es, /<html lang="es"/);
    assert.ok(titleOf(es) && titleOf(es) !== titleOf(en), 'a Spanish <title>');
    assert.ok(descOf(es) && descOf(es) !== descOf(en), 'a Spanish meta description');
    assert.equal(/'/.test(descOf(es)), false, 'no apostrophe in the description (some readers cut there)');
    assert.equal(canonOf(es), `${ORIGIN}/es${page.route}`);
    if (ogUrlOf(en)) assert.equal(ogUrlOf(es), canonOf(es), 'og:url is the canonical');
    for (const html of [en, es]) {
      assert.ok(html.includes(alternates(page.route)), 'en, es and x-default alternates');
    }
    const ld = /<script type="application\/ld\+json">([\s\S]*?)<\/script>/.exec(es)?.[1];
    assert.ok(ld, 'JSON-LD');
    const data = JSON.parse(ld);
    const nodes = data['@graph'] ?? [data];
    for (const node of nodes) {
      assert.equal(node.inLanguage, 'es');
      assert.ok(String(node.url).startsWith(`${ORIGIN}/es/`), `JSON-LD url ${node.url}`);
    }
  });

  test(`${page.route}: the switch links the two languages both ways`, () => {
    assert.ok(en.includes(langSwitch('en', page.route)), 'the English page links its Spanish twin');
    assert.ok(es.includes(langSwitch('es', page.route)), 'the Spanish page links back');
    for (const html of [en, es]) assert.match(html, /<script src="\/lang\.js" defer><\/script>/);
  });

  test(`${page.route}: the Spanish page keeps the page rules`, () => {
    const withoutLd = es
      .replace(/<style>[\s\S]*?<\/style>/g, '')
      .replace(/<script type="application\/ld\+json">[\s\S]*?<\/script>/g, '');
    assert.equal(/<script(?![^>]*\bsrc=)[^>]*>[\s\S]*?<\/script>/.test(withoutLd), false, 'no inline script');
    const enScripts = [...en.matchAll(/<script\b[^>]*\bsrc="([^"]+)"/g)].length;
    const esScripts = [...es.matchAll(/<script\b[^>]*\bsrc="([^"]+)"/g)].map((m) => m[1]);
    assert.equal(esScripts.length, enScripts, 'the same scripts as the English page');
    for (const src of esScripts) {
      assert.ok(src.startsWith('/') && !src.startsWith('//'), `script from this site only: ${src}`);
      assert.ok(existsSync(join(PUBLIC, src)), `the script exists: ${src}`);
    }
    for (const href of [...es.matchAll(/(?:href|src)="([^"]*)"/g)].map((m) => m[1])) {
      if (href.startsWith('#') || /^https?:/i.test(href)) continue;
      const path = href.split('#')[0].split('?')[0].replace(/\/$/, '/index.html');
      assert.ok(existsSync(join(PUBLIC, path)), `dead link on /es${page.route}: ${href}`);
    }
    for (const href of [...es.matchAll(/href="([^"]*)"/g)].map((m) => m[1])) {
      assert.ok(!/\.(exe|dmg|msi|AppImage|deb)(\?|#|$)/i.test(href), `a hardcoded download link: ${href}`);
    }
    // No English sentence survives in the words a reader sees (product names aside).
    const words = es.replace(/<(script|style)[\s\S]*?<\/\1>/g, '').replace(/<[^>]+>/g, ' ');
    for (const phrase of [' the ', ' your ', ' and the ', ' is not ', ' does not ']) {
      assert.equal(words.includes(phrase), false, `English left on /es${page.route}: "${phrase.trim()}"`);
    }
  });
}

